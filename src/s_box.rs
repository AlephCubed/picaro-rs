/// Applies the S-Box to a 112-bit number.
/// # Panics
/// If the number is larger than 112-bits.
pub(crate) fn s_box(state: u128) -> u128 {
    debug_assert_eq!(state >> 112, 0, "Must be an 112-bit number.");

    let mut bytes = state.to_be_bytes();

    for i in 2..16 {
        bytes[i] = S_BOX_FLAT[bytes[i] as usize];
    }

    u128::from_be_bytes(bytes)
}

fn sub_field_s_box(byte: u8) -> u8 {
    let y = byte >> 4;
    let x = byte & 0b1111;

    let x_out = nibble_mult::<PICARO_S_BOX>(x, y);

    let x3 = nibble_mult::<PICARO_S_BOX>(nibble_square::<PICARO_S_BOX>(x), x);
    let y3 = nibble_mult::<PICARO_S_BOX>(nibble_square::<PICARO_S_BOX>(y), y);
    let y_out = nibble_mult::<PICARO_S_BOX>(x3 ^ 0x02, y3 ^ 0x04);

    (x_out << 4) ^ y_out
}

fn masked_s_box<const SHARE_COUNT: usize>(
    shares: [u128; SHARE_COUNT],
    rng: &mut ChaCha20Rng,
) -> [u128; SHARE_COUNT] {
    let y = shares.map(|s| s >> 4);
    let x = shares.map(|s| s & 0b1111);

    let mut x_out = share_nibble_mult::<PICARO_S_BOX, SHARE_COUNT>(y, x, rng);

    let x3 = share_nibble_mult::<PICARO_S_BOX, SHARE_COUNT>(
        share_nibble_square::<PICARO_S_BOX, SHARE_COUNT>(x),
        x,
        rng,
    );

    let y3 = share_nibble_mult::<PICARO_S_BOX, SHARE_COUNT>(
        share_nibble_square::<PICARO_S_BOX, SHARE_COUNT>(y),
        y,
        rng,
    );

    let x3_shifted = x3.map(|s| s ^ 0x2);
    let y3_shifted = y3.map(|s| s ^ 0x4);
    let y_out = share_nibble_mult::<PICARO_S_BOX, SHARE_COUNT>(x3_shifted, y3_shifted, rng);

    for i in 0..SHARE_COUNT {
        x_out[i] = (x_out[i] << 4) ^ y_out[i];
    }

    x_out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::masking::{merge_u128, split_u128};
    use rand_chacha::rand_core::SeedableRng;

    #[test]
    fn min_value() {
        assert_eq!(s_box(0), 0x0808080808080808080808080808);
    }

    #[test]
    fn max_value() {
        assert_eq!(s_box(u128::MAX >> 16), 0x3535353535353535353535353535);
    }

    // First row, second column.
    #[test]
    fn one_value() {
        assert_eq!(s_box(0x1), 0x080808080808080808080808080c);
    }

    // Second row, first column.
    #[test]
    fn sixteen_value() {
        assert_eq!(s_box(0x10), 0x080808080808080808080808080a);
    }

    #[test]
    #[should_panic(expected = "Must be an 112-bit number.")]
    fn over_112_bits() {
        s_box(u128::MAX);
    }

    #[test]
    fn fields_match() {
        for i in 0..u8::MAX {
            assert_eq!(sub_field_s_box(i), S_BOX_FLAT[i as usize]);
        }
    }

    #[test]
    fn masked_matches() {
        let mut rng = ChaCha20Rng::seed_from_u64(12345);

        for i in 0..256 {
            let result = masked_s_box::<2>(split_u128(i, &mut rng), &mut rng);
            assert_eq!(merge_u128(result).to_be_bytes()[15], S_BOX_FLAT[i as usize]);
        }
    }
}
